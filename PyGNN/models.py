"""Feed-forward generative networks and their optimizer step."""

import math
from numbers import Integral

import torch
from torch import nn

from .losses import LossFun
from .sampling import draw_prior, draw_quasi_prior


class NormalQuantile(nn.Module):
    """Apply the N(mean, std**2) inverse CDF; inputs must lie strictly in (0, 1)."""

    def __init__(self, mean=0.0, std=1.0):
        super().__init__()
        if not math.isfinite(mean) or not math.isfinite(std) or std <= 0:
            raise ValueError("mean must be finite and std must be positive and finite.")
        self.mean, self.std = float(mean), float(std)

    def forward(self, x):
        """Transform probabilities on the input tensor's device and dtype."""
        return self.mean + self.std * math.sqrt(2) * torch.erfinv(2 * x - 1)


_ACTIVATIONS = {
    "ReLU": nn.ReLU,
    "LeakyReLU": nn.LeakyReLU,
    "Sigmoid": nn.Sigmoid,
    "NormalQuantile": NormalQuantile,
    "Tanhshrink": nn.Tanhshrink,
}


class FNN(nn.Module):
    """Feed-forward generator trained with an Adam optimizer.

    Args:
        dims: Input, hidden, and output widths (positive integers).
        activations: Names from ReLU, LeakyReLU, Sigmoid, NormalQuantile,
            Tanhshrink, or None, one per stage. Batch normalization precedes
            each activation.
        batch_norm: Apply BatchNorm1d after every stage, including the output.
        input_dist: N (standard normal), U (uniform), t (multivariate t4), or
            P (caller-supplied prior).
        loss_fun: MMD, tMMD, CvM, MSE, or BCE.
        MMD_normalized: Divide squared distances by observed dimension counts.
        drop_out: Dropout probability on hidden stages, in [0, 1).
        device: PyTorch device; defaults to CPU for portability.
        lrate: Positive Adam learning rate.

    The ``optimizer`` attribute exposes Adam and ``lossFun`` exposes the loss.
    """

    def __init__(self, dims, activations, batch_norm=False, input_dist="N",
                 loss_fun="MMD", MMD_normalized=False, drop_out=0,
                 device="cpu", lrate=1e-3):
        super().__init__()
        dims, activations = list(dims), list(activations)
        if len(dims) < 2:
            raise ValueError("dims must contain at least an input and output width.")
        for i, width in enumerate(dims):
            if not isinstance(width, Integral) or isinstance(width, bool) or width < 1:
                raise ValueError("Widths must be positive integers.")
            dims[i] = int(width)
        if len(activations) != len(dims) - 1:
            raise ValueError("Provide one activation entry per network stage; use None for no activation.")
        if any(name is not None and name not in _ACTIVATIONS for name in activations):
            raise ValueError(f"Supported activations: {tuple(_ACTIVATIONS)} and None.")
        if input_dist not in ("N", "U", "t", "P"):
            raise ValueError("input_dist must be N, U, t, or P.")
        if not isinstance(batch_norm, bool):
            raise TypeError("batch_norm must be a bool.")
        if not isinstance(drop_out, (int, float)) or not 0 <= drop_out < 1:
            raise ValueError("drop_out must be in [0, 1).")
        if not math.isfinite(lrate) or lrate <= 0:
            raise ValueError("lrate must be positive and finite.")

        self.dims = dims
        self.activations = activations
        self.inDist = input_dist
        self.batchNorm = batch_norm
        self.dropOut = float(drop_out)
        self.lossFun = LossFun(loss_fun, MMD_normalized)
        self.model = nn.Sequential()
        width = dims[0]
        for i, next_width in enumerate(dims[1:], start=1):
            self.model.add_module(f"Dense{i}", nn.Linear(width, next_width))
            width = next_width
            if batch_norm:
                self.model.add_module(f"BN{i}", nn.BatchNorm1d(width))
            if activations[i - 1] is not None:
                self.model.add_module(f"Acti{i}", _ACTIVATIONS[activations[i - 1]]())
            if self.dropOut and i < len(dims) - 1:
                self.model.add_module(f"Dropout{i}", nn.Dropout(self.dropOut))
        self.to(device)
        self.optimizer = torch.optim.Adam(self.parameters(), lr=lrate)

    @property
    def device(self):
        """Current parameter device, also reflecting later calls to ``to()``."""
        return str(next(self.parameters()).device)

    @property
    def output_dim(self):
        """Number of coordinates generated by the network."""
        return self.dims[-1]

    def configuration(self):
        """Return constructor arguments for recreating this model."""
        return {
            "dims": self.dims.copy(), "activations": self.activations.copy(),
            "batch_norm": self.batchNorm, "input_dist": self.inDist,
            "loss_fun": self.lossFun.name, "MMD_normalized": self.lossFun.normalized,
            "drop_out": self.dropOut, "device": self.device,
            "lrate": self.optimizer.param_groups[0]["lr"],
        }

    def forward(self, x):
        """Map an ``(n, input_dim)`` tensor onto the model's device and dtype."""
        if not isinstance(x, torch.Tensor) or x.ndim != 2 or x.shape[1] != self.dims[0]:
            raise ValueError(f"x must be a tensor with shape (n, {self.dims[0]}).")
        parameter = next(self.parameters())
        return self.model(x.to(device=parameter.device, dtype=parameter.dtype))

    def step(self, x, y, *, bandwidth=None, weight=None):
        """Take one Adam step and return a detached scalar loss tensor.

        Detaching the return value prevents the epoch accumulator from
        retaining graphs.
        """
        self.train()
        parameter = next(self.parameters())
        y = y.to(device=parameter.device, dtype=parameter.dtype)
        self.optimizer.zero_grad(set_to_none=True)
        loss = self.lossFun(self(x), y, bandwidth, weight)
        if not torch.isfinite(loss):
            raise FloatingPointError("Training loss is nonfinite; check data, activations, and bandwidths.")
        loss.backward()
        self.optimizer.step()
        return loss.detach()

    def sample(self, size, QRS=False, seed=None, generator=None):
        """Generate an ``(size, output_dim)`` sample through this network.

        ``seed`` reproduces pseudo-random draws or a Sobol' scramble. A supplied
        torch generator controls pseudo-random draws. Supply only one of seed
        and generator. This method preserves autograd and the current training
        mode; call ``eval()`` and use ``torch.no_grad()`` for inference.
        """
        if self.inDist == "P":
            raise NotImplementedError("For prior P, call model(explicit_prior_samples).")
        if seed is not None and generator is not None:
            raise ValueError("Supply seed or generator, not both.")
        if QRS and generator is not None:
            raise ValueError("QRS uses seed for its scramble, not a torch generator.")
        if QRS:
            x = draw_quasi_prior(self.inDist, self.dims[0], size,
                                 device=self.device, seed=seed)
        else:
            if seed is not None:
                generator = torch.Generator().manual_seed(seed)
            x = draw_prior(self.inDist, self.dims[0], size, device=self.device,
                           generator=generator)
        return self(x)
